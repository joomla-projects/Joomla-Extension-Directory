/**
 * The inbound feeds.
 *
 * @since 4.0.0
 */
enum FeedSource: string
{
    case CNA = 'cna';
    case NVD = 'nvd';

    /**
     * @return string  Language key.
     *
     * @since 4.0.0
     */
    public function label(): string
    {
        return 'COM_VEL_FEED_SOURCE_' . strtoupper($this->value);
    }
}
